test("注入的 runPack 以 { cwd: root } 被调用一次（缺省执行器是真 npm pack）", async () => {
  const root = await makeProject({ existing: [] });
  const runPack = fakePack({ generated: [] });

  assert.equal(checkPackLinks({ root, runPack }), 0);
  assert.deepEqual(runPack.calls, [root], "只跑一次 pack，cwd 就是注入的 root");
  assert.equal(typeof runNpmPackDryRun, "function");
});

test("被 import 时零副作用：只有被当命令直接跑才执行门禁", async () => {
  const root = await makeProject({ existing: [] });
  const scriptUrl = new URL("../scripts/pack-link-check.mjs", import.meta.url).href;
  const importer = path.join(root, "importer.mjs");
  await writeFile(
    importer,
    `import { checkPackLinks, runNpmPackDryRun } from ${JSON.stringify(scriptUrl)};\n`
    + "process.stdout.write(`${typeof checkPackLinks}/${typeof runNpmPackDryRun}/${String(process.exitCode)}`);\n",
    "utf8",
  );

  const child = spawnSync(process.execPath, [importer], { cwd: root, encoding: "utf8" });

  assert.equal(child.status, 0, `stderr=${child.stderr}`);
  assert.equal(
    child.stdout,
    "function/function/undefined",
    "import 不得跑门禁：process.exitCode 必须仍是 undefined，且不能有输出",
  );
  assert.equal(existsSync(path.join(root, "src")), true, "import 也不该动 src/");
});

// ── 共享小工具本身 ─────────────────────────────────────────────────────────

test("listDeclarationFiles：递归、只认 .d.ts、结果有序；没有 src/ 时为空", async () => {
  const root = await makeProject({
    existing: ["src/index.d.ts", "src/deep/nested/tool.d.ts", "src/index.js", "README.md"],
  });
  await writeFile(path.join(root, "src", "notes.txt"), "x\n", "utf8");

  const found = listDeclarationFiles(root);
  assert.deepEqual(found, [...found].sort());
  assert.deepEqual(
    found.map((abs) => path.relative(root, abs).split(path.sep).join("/")),
    ["src/deep/nested/tool.d.ts", "src/index.d.ts"],
  );

  const emptyRoot = await makeTmp("268-no-src-");
  assert.deepEqual(listDeclarationFiles(emptyRoot), [], "src/ 不存在时返回空数组而不是抛错");
});

test("reclaimGeneratedDeclarations：只删 before 之外的；kept 如实；目录名以 .d.ts 结尾不算文件", async () => {
  const root = await makeProject({ existing: ["src/keep.d.ts"] });
  const before = listDeclarationFiles(root); // 此刻只有 src/keep.d.ts
  mkdirSync(path.join(root, "src", "nested.d.ts"), { recursive: true });
  writeFileSync(path.join(root, "src", "nested.d.ts", "inner.d.ts"), "// gen\n", "utf8");
  writeFileSync(path.join(root, "src", "generated.d.ts"), "// gen\n", "utf8");

  assert.deepEqual(
    before.map((abs) => path.relative(root, abs).split(path.sep).join("/")),
    ["src/keep.d.ts"],
    "叫 nested.d.ts 的**目录**本身不是声明文件，但要递归进去找 inner.d.ts",
  );

  const result = reclaimGeneratedDeclarations({ root, before });

  assert.deepEqual(
    result.removed,
    ["src/generated.d.ts", "src/nested.d.ts/inner.d.ts"],
    "removed = 相对 root 的 posix 路径，且只含本次新出现的",
  );
  assert.equal(result.kept, 1, "跑前已存在且没动的数量");
  assert.deepEqual(result.failed, [], "没有删不掉的文件时 failed 为空");
  assert.equal(existsSync(path.join(root, "src", "generated.d.ts")), false);
  assert.equal(existsSync(path.join(root, "src", "nested.d.ts", "inner.d.ts")), false);
  assert.equal(existsSync(path.join(root, "src", "keep.d.ts")), true);

  // before 为空 = 在场的全都算本次产物（跑前 src/ 下本来就没有 .d.ts 的真实情形）
  rmSync(path.join(root, "src", "keep.d.ts"), { force: true });
  writeFileSync(path.join(root, "src", "late.d.ts"), "// gen\n", "utf8");
  const all = reclaimGeneratedDeclarations({ root, before: [] });
  assert.deepEqual(all.removed, ["src/late.d.ts"]);
  assert.equal(all.kept, 0);
});
