// 覆盖 scripts/pack-link-check.mjs 与 scripts/generated-declarations.mjs（issue #268：
// 门禁互相投毒 —— `npm pack` 触发的 `prepack` 往 src/ 留下约 61 个 .d.ts，紧随的 check:types
// 被陈旧声明守卫（issue #214）硬失败）。
//
// 可测性口径：`checkPackLinks({ root, runPack })` 的 `runPack` 可注入，测试里的「假 pack」
// 就是**假 prepack**——在 <root>/src 下写出 .d.ts，然后返回一份 npm pack --json 形状的结果。
// 于是不 spawn 真 npm、不碰网络，也能真的验到「新生成物被回收 / 跑前已存在的保留」这两条不变量。
//
// 仓内既有测试：#268 之前 test/ 里没有任何引用 pack-link 的用例（`grep -rl pack-link test/` 为空），
// 所以本文件是新增锚点，不是成对更新。
import test from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  checkPackLinks,
  runNpmPackDryRun,
} from "../scripts/pack-link-check.mjs";
import {
  listDeclarationFiles,
  reclaimGeneratedDeclarations,
} from "../scripts/generated-declarations.mjs";
import { makeTmp } from "./helpers/tmp.js";

const PACK_OK_JSON = JSON.stringify([{ files: [{ path: "package/src/index.js" }] }]);

/** 造一个假仓库根：只有 src/ 与调用方点名的「跑前就已存在」的文件。 */
async function makeProject({ existing = [] } = {}) {
  const root = await makeTmp("268-pack-links-");
  await mkdir(path.join(root, "src"), { recursive: true });
  for (const rel of existing) {
    const abs = path.join(root, rel);
    await mkdir(path.dirname(abs), { recursive: true });
    await writeFile(abs, `// pre-existing: ${rel}\n`, "utf8");
  }
  return root;
}

/**
 * 假 pack：模拟 `prepack` 在 <cwd>/src 下写出声明文件，然后返回 spawnSync 形状的结果。
 *
 * @param {{ generated?: string[], result?: object, error?: Error }} params
 * @returns {((params: { cwd: string }) => object) & { calls: string[], saw: Record<string, boolean> }}
 */
function fakePack({ generated = [], result, error } = {}) {
  const runPack = ({ cwd }) => {
    runPack.calls.push(cwd);
    for (const rel of generated) {
      const abs = path.join(cwd, rel);
      mkdirSync(path.dirname(abs), { recursive: true });
      writeFileSync(abs, `// generated by fake prepack: ${rel}\n`, "utf8");
      runPack.saw[rel] = existsSync(abs); // 假 prepack 写完了，门禁此刻看得见它
    }
    if (error) throw error;
    return result ?? { status: 0, stdout: PACK_OK_JSON, stderr: "" };
  };
  runPack.calls = [];
  runPack.saw = {};
  return runPack;
}

/** 抓 console 三个出口 + 返回值。 */
function capture(fn) {
  const original = { log: console.log, error: console.error, warn: console.warn };
  const out = { code: undefined, stdout: [], stderr: [], warn: [] };
  console.log = (...args) => out.stdout.push(args.join(" "));
  console.error = (...args) => out.stderr.push(args.join(" "));
  console.warn = (...args) => out.warn.push(args.join(" "));
  try {
    out.code = fn();
  } finally {
    Object.assign(console, original);
  }
  return out;
}

// ── 不变量 1：只回收本次新生成的 ─────────────────────────────────────────────

test("prepack 新生成的 .d.ts 在 checkPackLinks 返回前被回收", async () => {
  const root = await makeProject({ existing: ["src/keep.d.ts"] });
  const runPack = fakePack({ generated: ["src/generated.d.ts"] });

  const exitCode = checkPackLinks({ root, runPack });

  assert.equal(exitCode, 0, "链接闭合判定本身应通过");
  assert.equal(runPack.saw["src/generated.d.ts"], true, "假 prepack 确实写出过它");
  assert.equal(
    existsSync(path.join(root, "src", "generated.d.ts")),
    false,
    "本次新生成的 .d.ts 必须被回收（否则 check:types 必红，issue #268）",
  );
});

test("跑前就已存在的 .d.ts 一律保留，内容也不许被动", async () => {
  const root = await makeProject({ existing: ["src/keep.d.ts", "src/deep/older.d.ts"] });
  const keepAbs = path.join(root, "src", "keep.d.ts");
  const before = readFileSync(keepAbs, "utf8");
  const runPack = fakePack({ generated: ["src/generated.d.ts"] });

  const exitCode = checkPackLinks({ root, runPack });

  assert.equal(exitCode, 0);
  assert.equal(existsSync(keepAbs), true, "跑前已存在的声明文件是用户有意 types:build 留下的，不许删");
  assert.equal(existsSync(path.join(root, "src", "deep", "older.d.ts")), true);
  assert.equal(
    readFileSync(keepAbs, "utf8"),
    before,
    "保留 = 内容逐字不变（本模块只删文件，不重写文件）",
  );
});

test("嵌套子目录里的新生成物同样被回收", async () => {
  const root = await makeProject({ existing: [] });
  const runPack = fakePack({
    generated: ["src/deep/nested/tool.d.ts", "src/index.d.ts"],
  });

  assert.equal(checkPackLinks({ root, runPack }), 0);
  assert.deepEqual(listDeclarationFiles(root), [], "src/ 下应一个 .d.ts 都不剩");
});

test("没有任何新生成物时零删除（预先存在的一个都不动）", async () => {
  const root = await makeProject({ existing: ["src/index.d.ts", "src/deep/keep.d.ts"] });
  const before = listDeclarationFiles(root);
  const runPack = fakePack({ generated: [] });

  const out = capture(() => checkPackLinks({ root, runPack }));

  assert.equal(out.code, 0);
  assert.deepEqual(listDeclarationFiles(root), before, "清点结果必须与跑前完全一致");
  assert.equal(
    out.stderr.some((line) => line.includes("已回收")),
    false,
    "没删东西就不该声称自己删了",
  );
});

// ── 不变量 2：原始失败原样传出，清理不许吞掉它 ────────────────────────────────

test("npm pack 退出码非 0：照样清理，且原始 npm 报错原样传出", async () => {
  const root = await makeProject({ existing: ["src/keep.d.ts"] });
  const runPack = fakePack({
    generated: ["src/generated.d.ts"],
    result: { status: 1, stdout: "", stderr: "npm ERR! prepack exited with a non-zero code\n" },
  });

  const out = capture(() => checkPackLinks({ root, runPack }));

  assert.equal(out.code, 1, "原始失败要以非零退出码传出");
  assert.match(out.stderr.join("\n"), /npm pack failed \(exit 1\)/);
  assert.match(out.stderr.join("\n"), /prepack exited with a non-zero code/, "npm 自己的 stderr 不许被替换");
  assert.equal(existsSync(path.join(root, "src", "generated.d.ts")), false, "失败路径也必须清理");
  assert.equal(existsSync(path.join(root, "src", "keep.d.ts")), true);
});

test("runPack 抛错：照样清理，且原始错误信息原样传出（退出码 1）", async () => {
  const root = await makeProject({ existing: ["src/keep.d.ts"] });
  const runPack = fakePack({
    generated: ["src/generated.d.ts"],
    error: new Error("npm binary is missing from PATH"),
  });

  const out = capture(() => checkPackLinks({ root, runPack }));

  assert.equal(out.code, 1);
  assert.match(out.stderr.join("\n"), /failed to run npm pack: npm binary is missing from PATH/);
  assert.equal(existsSync(path.join(root, "src", "generated.d.ts")), false);
  assert.equal(existsSync(path.join(root, "src", "keep.d.ts")), true);
});

test("链接闭合判定为红（dead link）时也执行清理", async () => {
  const root = await makeProject({ existing: ["src/keep.d.ts"] });
  await mkdir(path.join(root, "scripts"), { recursive: true });
  await writeFile(path.join(root, "scripts", "omitted.mjs"), "export const x = 1;\n", "utf8");
  await writeFile(
    path.join(root, "README.md"),
    "# fake\n\n[omitted](./scripts/omitted.mjs)\n",
    "utf8",
  );
  const runPack = fakePack({
    generated: ["src/generated.d.ts"],
    result: {
      status: 0,
      stdout: JSON.stringify([
        { files: [{ path: "package/README.md" }, { path: "package/src/index.js" }] },
      ]),
      stderr: "",
    },
  });

  const out = capture(() => checkPackLinks({ root, runPack }));

  assert.equal(out.code, 1, "指向未随包文件的链接是 blocking");
  assert.match(out.stderr.join("\n"), /dead link/);
  assert.equal(existsSync(path.join(root, "src", "generated.d.ts")), false);
  assert.equal(existsSync(path.join(root, "src", "keep.d.ts")), true);
});

