/** 写一份带「装包应列 N 个 .d.ts」声称的入口文档。 */
async function writeClaimDoc(root, rel, text) {
  const abs = path.join(root, rel);
  await mkdir(path.dirname(abs), { recursive: true });
  await writeFile(abs, text, "utf8");
  return abs;
}

